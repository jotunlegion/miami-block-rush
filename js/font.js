  const keys = Object.keys(G);
  const index = {};
  keys.forEach((k, i) => (index[k] = i));
  const atlases = {};

  function atlas(color) {
    if (atlases[color]) return atlases[color];
    const c = document.createElement('canvas');
    c.width = keys.length * 5;
    c.height = 7;
    const x = c.getContext('2d');
    x.fillStyle = color;
    keys.forEach((k, i) => {
      const rows = G[k].split('|');
      for (let r = 0; r < 7; r++)
        for (let q = 0; q < 5; q++) if (rows[r][q] === '#') x.fillRect(i * 5 + q, r, 1, 1);
    });
    atlases[color] = c;
    return c;
  }

  function glyphOf(ch) {
    ch = ch.toUpperCase();
    if (ALIAS[ch]) ch = ALIAS[ch];
    return index[ch];
  }

  function measure(str, s = 1) {
    return Math.max(0, str.length * 6 * s - s);
  }

  // draw text; align: 'left' | 'center' | 'right'; shadow: color or null
  function draw(ctx, str, x, y, color = '#fff', s = 1, align = 'left', shadow = '#1a0a2e') {
    str = String(str);
    let w = measure(str, s);
    x = Math.round(align === 'center' ? x - w / 2 : align === 'right' ? x - w : x);
    y = Math.round(y);
    const so = s >= 3 ? 2 : 1;
    if (shadow) drawRaw(ctx, str, x + so, y + so, shadow, s);
    drawRaw(ctx, str, x, y, color, s);
  }

  function drawRaw(ctx, str, x, y, color, s) {
    const a = atlas(color);
    for (let i = 0; i < str.length; i++) {
      const g = glyphOf(str[i]);
      if (g === undefined) continue;
      ctx.drawImage(a, g * 5, 0, 5, 7, x + i * 6 * s, y, 5 * s, 7 * s);
    }
  }

  window.Font = { draw, measure };
